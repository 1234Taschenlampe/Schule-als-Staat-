/**
 * Build the canonical Cloudflare Workers Free website with a same-origin PDF proxy.
 * Run: node scripts/build-worker.mjs
 * Output: dist/schule-als-staat-worker.js
 * No Adobe API or paid services.
 */
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve, dirname } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const names = [
  "index.html", "styles.css", "features.css", "tutorial.css",
  "brand-emblem.css", "public-visa.css", "shop-plan.css",
  "app.js", "features.js", "roles.js", "attendance.js", "tutorial.js",
  "config.js", "work-hours.js", "shop-management.js",
  "admin-credit.js", "public-visa.js", "shop-plan.js"
];
const files = Object.fromEntries(
  names.map(name => ["/" + name, readFileSync(resolve(root, name), "utf8")])
);
const types = Object.fromEntries(names.map(name => [
  "/" + name,
  name.endsWith(".html") ? "text/html; charset=utf-8"
    : name.endsWith(".css") ? "text/css; charset=utf-8"
    : "application/javascript; charset=utf-8"
]));
const config = readFileSync(resolve(root, "config.js"), "utf8");
const url = /supabaseUrl:\s*"([^"]+)"/.exec(config)?.[1];
const publishableKey = /supabaseAnonKey:\s*"([^"]+)"/.exec(config)?.[1];
if (!/^https:\/\/[a-z0-9-]+\.supabase\.co$/.test(url || "") ||
    !/^sb_publishable_[A-Za-z0-9_-]+$/.test(publishableKey || ""))
  throw new Error("Missing public Supabase routing configuration");
const overlordSource = readFileSync(resolve(root, "overlord-edge.js"), "utf8");
const worker = [
  "/* Generated by scripts/build-worker.mjs. No API keys or paid dependencies. */",
  "const ASSETS=" + JSON.stringify(files) + ";",
  "const TYPES=" + JSON.stringify(types) + ";",
  "const OVERLORD_SUPABASE_URL=" + JSON.stringify(url) + ";",
  "const OVERLORD_PUBLISHABLE_KEY=" + JSON.stringify(publishableKey) + ";",
  overlordSource,
  "addEventListener('fetch',event=>event.respondWith((async()=>{",
  "const url=new URL(event.request.url),path=url.pathname==='/'?'/index.html':url.pathname;",
  "if(path.startsWith('/api/v1/'))return overlordHandle(event.request);",
  "if(!['GET','HEAD'].includes(event.request.method))return new Response('Method Not Allowed',{status:405,headers:{Allow:'GET,HEAD'}});",
  "if(path==='/rng-floorplan.pdf'){",
  "try{",
  "const upstream=await fetch('https://www.rng-wangen.de/wp-content/uploads/2024/07/230625_digitaler-uebersichtsplan.pdf',{",
  "method:event.request.method,headers:{Accept:'application/pdf'},redirect:'follow',cf:{cacheEverything:true,cacheTtl:86400}",
  "});",
  "if(!upstream.ok)return new Response('Schulplan vorübergehend nicht abrufbar',{status:502});",
  "const contentType=upstream.headers.get('content-type')||'';",
  "if(!/pdf|octet-stream/i.test(contentType))return new Response('Kein PDF vom Schulserver erhalten',{status:502});",
  "return new Response(event.request.method==='HEAD'?null:upstream.body,{status:200,headers:{",
  "'Content-Type':'application/pdf','Cache-Control':'public,max-age=86400',",
  "'Content-Disposition':'inline; filename=\"rng-schulplan.pdf\"','X-Content-Type-Options':'nosniff'",
  "}});",
  "}catch(e){return new Response('Der Schulplan konnte nicht geladen werden.',{status:502});}",
  "}",
  "if(!(path in ASSETS))return new Response('Not Found',{status:404,headers:{'X-Content-Type-Options':'nosniff'}});",
  "const headers={",
  "'Content-Type':TYPES[path],",
  "'X-Content-Type-Options':'nosniff',",
  "'Referrer-Policy':'strict-origin-when-cross-origin',",
  "'X-Frame-Options':'DENY',",
  "'Permissions-Policy':'camera=(self),microphone=()',",
  "'Strict-Transport-Security':'max-age=31536000; includeSubDomains',",
  "'Cache-Control':'no-store',",
  "'Content-Security-Policy':\"default-src 'self'; script-src 'self' https://cdn.jsdelivr.net https://challenges.cloudflare.com; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; connect-src 'self' https://challenges.cloudflare.com https://wdebwgcferieedkpqbvk.supabase.co wss://wdebwgcferieedkpqbvk.supabase.co; media-src 'self' blob:; font-src 'self' data: blob:; object-src 'none'; base-uri 'self'; frame-src 'self' https://challenges.cloudflare.com; worker-src 'self' blob: https://cdn.jsdelivr.net; frame-ancestors 'none'; form-action 'self'\"",
  "};",
  "return new Response(event.request.method==='HEAD'?null:ASSETS[path],{status:200,headers});",
  "})()));",
  ""
].join("\n");

mkdirSync(resolve(root, "dist"), { recursive: true });
writeFileSync(resolve(root, "dist/schule-als-staat-worker.js"), worker, "utf8");
console.log("Generated Cloudflare Worker with " + names.length + " public assets (" + worker.length + " characters).");
