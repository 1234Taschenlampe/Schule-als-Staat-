/**
 * Generate a self-contained Cloudflare Workers Free fallback.
 * No dependencies, no secret keys, no paid services, no automatic deploy.
 * Run: node scripts/build-worker.mjs
 * Output: dist/schule-als-staat-worker.js
 *
 * Cloudflare Workers Free is the sole official live site; GitHub Pages redirects to it.
 * This bundle serves only unified, real V4/V6 assets; old V3 demos are not public.
 */
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve, dirname } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const names = ["index.html", "styles.css", "features.css", "verification.css", "tutorial.css", "app.js", "features.js", "verification.js", "roles.js", "attendance.js", "tutorial.js", "config.js"];
const files = Object.fromEntries(
  names.map((name) => ["/" + name, readFileSync(resolve(root, name), "utf8")])
);

const headers = {
  "/index.html": "text/html; charset=utf-8",
  "/styles.css": "text/css; charset=utf-8",
  "/features.css": "text/css; charset=utf-8",
  "/verification.css": "text/css; charset=utf-8",
  "/tutorial.css": "text/css; charset=utf-8",
  "/app.js": "application/javascript; charset=utf-8",
  "/features.js": "application/javascript; charset=utf-8",
  "/verification.js": "application/javascript; charset=utf-8",
  "/roles.js": "application/javascript; charset=utf-8",
  "/attendance.js": "application/javascript; charset=utf-8",
  "/tutorial.js": "application/javascript; charset=utf-8",
  "/config.js": "application/javascript; charset=utf-8"
};

const worker = [
  "/* Generated by scripts/build-worker.mjs. Do not manually edit. */",
  "const ASSETS=" + JSON.stringify(files) + ";",
  "const TYPES=" + JSON.stringify(headers) + ";",
  "addEventListener('fetch', event => {",
  "  event.respondWith((() => {",
  "    const url = new URL(event.request.url);",
  "    const path = url.pathname === '/' ? '/index.html' : url.pathname;",
  "    if (!['GET','HEAD'].includes(event.request.method)) return new Response('Method not allowed',{status:405,headers:{Allow:'GET, HEAD'}});",
  "    if (!(path in ASSETS)) return new Response('Not found',{status:404,headers:{'X-Content-Type-Options':'nosniff'}});",
  "    const responseHeaders = {",
  "      'Content-Type': TYPES[path],",
  "      'X-Content-Type-Options': 'nosniff',",
  "      'Referrer-Policy': 'strict-origin-when-cross-origin',",
  "      'X-Frame-Options': 'DENY',",
  "      'Permissions-Policy': 'camera=(self), microphone=()',",
  "      'Strict-Transport-Security': 'max-age=31536000; includeSubDomains',",
  "      'Cache-Control': 'no-store',",
  "      'Content-Security-Policy': \"default-src 'self'; script-src 'self' https://cdn.jsdelivr.net; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; connect-src 'self' https://wdebwgcferieedkpqbvk.supabase.co wss://wdebwgcferieedkpqbvk.supabase.co; media-src 'self' blob:; object-src 'none'; base-uri 'self'; frame-ancestors 'none'; form-action 'self'\",",
  "    };",
  "    return new Response(event.request.method === 'HEAD' ? null : ASSETS[path], {status:200,headers:responseHeaders});",
  "  })());",
  "});",
  ""
].join("\n");

mkdirSync(resolve(root, "dist"), { recursive: true });
writeFileSync(resolve(root, "dist/schule-als-staat-worker.js"), worker, "utf8");
console.log("Generated Cloudflare Worker with " + names.length + " public files (" + worker.length + " chars).");
